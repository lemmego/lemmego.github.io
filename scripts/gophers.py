import os, re, subprocess, sys, json

RAW, DEST, DATA = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(DEST, exist_ok=True)

node_bin = "/Users/tanmay/Library/Application Support/Herd/config/nvm/versions/node/v22.22.3/bin"
env = dict(os.environ, PATH=node_bin + os.pathsep + os.environ["PATH"])

# svgo strips the Inkscape/RDF metadata these were authored with, which is
# most of their weight and none of their picture.
subprocess.run(["npx", "-y", "svgo@3.3.2", "--multipass", "-f", RAW, "-o", DEST],
               env=env, check=True, capture_output=True)

dims = {}
for name in sorted(os.listdir(DEST)):
    if not name.endswith(".svg"):
        continue
    head = open(os.path.join(DEST, name), encoding="utf-8").read(2000)
    m = re.search(r'viewBox="\s*([-\d.]+)[ ,]+([-\d.]+)[ ,]+([-\d.]+)[ ,]+([-\d.]+)', head)
    if not m:
        print("NO VIEWBOX:", name); continue
    w, h = float(m.group(3)), float(m.group(4))
    dims[name[:-4]] = {"w": round(w, 2), "h": round(h, 2)}

with open(DATA, "w", encoding="utf-8") as f:
    f.write("# Generated by scripts/gophers.py - do not edit by hand.\n")
    f.write("# Intrinsic size of each vendored gopher, so the <img> can carry real\n")
    f.write("# width and height attributes and reserve its space before it loads.\n")
    for k in sorted(dims):
        f.write(f"{k}:\n  w: {dims[k]['w']}\n  h: {dims[k]['h']}\n")

total = sum(os.path.getsize(os.path.join(DEST, n)) for n in os.listdir(DEST) if n.endswith(".svg"))
print(f"{len(dims)} gophers, {total//1024}KB total")
